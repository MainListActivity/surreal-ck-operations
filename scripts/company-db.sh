#!/bin/sh
# Owner-run, idempotent: sh scripts/company-db.sh install
# Runs the company control-plane database on this Mac (the company fork binary, loopback only) and schedules its off-site
# backup to R2. The data directory and the root password live under private/, which the employee sandbox cannot read.
#   org.surrealck.company-db      the database, kept alive by launchd
#   org.surrealck.company-backup  hourly export → zstd → R2 (scripts/company-backup.ts backup)
#   org.surrealck.company-verify  weekly restore drill of the newest backup (scripts/company-backup.ts verify)
# The jobs run from the checkout this script is run in (WorkingDirectory and scripts/company-backup.ts): re-run install after moving it.
set -eu
service=${SCK_SERVICE_HOME:-$HOME/Library/Application Support/SurrealCKCompany}
surreal=${SCK_SURREAL_BIN:-$HOME/.surrealdb/surreal}
port=${SCK_COMPANY_DB_PORT:-38480}
agents=$HOME/Library/LaunchAgents
repo=$(cd "$(dirname "$0")/.." && pwd)
creds="$service/private/company-db.env"

[ "${1:-}" = install ] || { echo "usage: sh scripts/company-db.sh install" >&2; exit 2; }
[ -x "$surreal" ] || { echo "company fork binary missing: $surreal" >&2; exit 1; }
umask 077
mkdir -p "$service/private/db" "$service/backups" "$service/logs" "$service/bin"
if [ ! -f "$creds" ]; then
  pass=$(/usr/bin/openssl rand -hex 24)
  printf 'SURREAL_URL=ws://127.0.0.1:%s/rpc\nSURREAL_ROOT_USER=root\nSURREAL_ROOT_PASS=%s\n' "$port" "$pass" > "$creds"
  unset pass
fi
chmod 600 "$creds"

cp "$(dirname "$0")/company-db-runtime.sh" "$service/bin/company-db-runtime"
chmod 700 "$service/bin/company-db-runtime"

cat > "$service/bin/company-db" <<EOF
#!/bin/sh
# Generated by scripts/company-db.sh: credentials come from private/company-db.env through the environment, never argv.
set -eu
export SURREAL_USER=\$(/usr/bin/sed -n 's/^SURREAL_ROOT_USER=//p' "$creds")
export SURREAL_PASS=\$(/usr/bin/sed -n 's/^SURREAL_ROOT_PASS=//p' "$creds")
exec /bin/sh "$service/bin/company-db-runtime" "$surreal" "127.0.0.1:$port" "$service/private/db"
EOF
chmod 700 "$service/bin/company-db"

plist() { # plist <label> <schedule xml> <program args xml>
  cat > "$agents/$1.plist.tmp" <<EOF
<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0"><dict>
  <key>Label</key><string>$1</string>
  <key>ProgramArguments</key><array>$3</array>
  <key>WorkingDirectory</key><string>$repo</string>
  $2
  <key>StandardOutPath</key><string>$service/logs/$1.log</string>
  <key>StandardErrorPath</key><string>$service/logs/$1.log</string>
</dict></plist>
EOF
  mv "$agents/$1.plist.tmp" "$agents/$1.plist"
  launchctl bootout "gui/$(id -u)/$1" 2>/dev/null || true
  launchctl bootstrap "gui/$(id -u)" "$agents/$1.plist"
}
bun="$service/runtime-bun/bin/bun"
backup="$repo/scripts/company-backup.ts"
plist org.surrealck.company-db '<key>RunAtLoad</key><true/><key>KeepAlive</key><true/>' "<string>$service/bin/company-db</string>"
for n in $(seq 1 100); do curl -sf "http://127.0.0.1:$port/health" >/dev/null && break; sleep 0.2; done
curl -sf "http://127.0.0.1:$port/health" >/dev/null || { echo "company db did not come up on 127.0.0.1:$port" >&2; exit 1; }
plist org.surrealck.company-backup '<key>StartInterval</key><integer>3600</integer>' "<string>$bun</string><string>$backup</string><string>backup</string>"
plist org.surrealck.company-verify '<key>StartCalendarInterval</key><dict><key>Weekday</key><integer>0</integer><key>Hour</key><integer>4</integer><key>Minute</key><integer>17</integer></dict>' "<string>$bun</string><string>$backup</string><string>verify</string>"
echo "company db on 127.0.0.1:$port; hourly R2 backup and weekly restore drill scheduled"
