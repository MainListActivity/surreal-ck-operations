import { join, resolve } from 'node:path';
import { homedir } from 'node:os';
import { RecordId } from 'surrealdb';
import { loadDatabaseConfig } from '../config';
import { SurrealCompanyCore } from '../core';
import { createPaseoCli, createSceneCleaner } from '../dispatcher/paseo';
import { createSubmitCheck } from '../pr-gate';
import { createSystemCheck } from '../submit-checks';
import { ensureNodeId } from '../node-identity';
import { CompanyDatabase } from '../database';
import { Workforce } from '../workforce';
import { readPrivateCredential } from './credential-file';
import { createGhCliGateway, createGithubProjector } from './github-projector';
import { runProjectionWorker } from './projector-worker';
import { createMcpHttpService } from './server';
import { installNodeHost } from '../host-node';

installNodeHost();

const rawPort = process.env.SCK_MCP_PORT;
if (!rawPort || !/^[0-9]+$/.test(rawPort)) throw new Error('SCK_MCP_PORT is required');
const port = Number(rawPort);
if (!Number.isSafeInteger(port) || port < 1 || port > 65535) throw new Error('invalid SCK_MCP_PORT');

const db = new CompanyDatabase(loadDatabaseConfig());
await db.connect();
let service: ReturnType<typeof createMcpHttpService> | undefined;
const shutdown = new AbortController();
try {
  // A wedged bootstrap must not leave a silent idle process; fail and let launchd retry.
  let bootTimer: ReturnType<typeof setTimeout> | undefined;
  try {
    await Promise.race([
      db.bootstrap(),
      new Promise<never>((_, reject) => {
        bootTimer = setTimeout(() => reject(new Error('bootstrap timed out after 90s')), 90_000);
      }),
    ]);
  } finally {
    clearTimeout(bootTimer);
  }
  // Workforce powers the manage-only def_* tools; its credential dir is unused by def writes.
  const workforce = new Workforce(db, resolve(process.env.SCK_CREDENTIAL_DIR ?? join(import.meta.dir, '..', '..', '.runtime', 'credentials')));
  // Snapshot build costs go to the service log, so a slow first page names its phase (load, reserve, write, commit) instead of
  // only its deadline (SYS01 AC02 production return). One line per build; no task text is included.
  const snapshotObserve = (stats: { outcome: string; kind: string; rows: number; bytes: number; batches: number; loadMs: number; reserveMs: number; writeMs: number; commitMs: number; totalMs: number; serverMs: number; loadAttempts: number; release: string; releaseMs: number }) =>
    console.log(`snapshot build ${stats.kind} ${stats.outcome} rows=${stats.rows} bytes=${stats.bytes} batches=${stats.batches} load=${Math.round(stats.loadMs)} reserve=${Math.round(stats.reserveMs)} write=${Math.round(stats.writeMs)} commit=${Math.round(stats.commitMs)} server=${Math.round(stats.serverMs)} total=${Math.round(stats.totalMs)} reads=${stats.loadAttempts} release=${stats.release} releaseMs=${Math.round(stats.releaseMs)}`);
  const serviceHome = process.env.SCK_SERVICE_HOME || join(homedir(), 'Library/Application Support/SurrealCKCompany');
  const core = new SurrealCompanyCore(db, { workforce, snapshotObserve, nodeId: ensureNodeId(serviceHome), submitCheck: process.env.SCK_PR_GATE === '0' ? undefined : createSubmitCheck(), systemCheck: process.env.SCK_SUBMIT_CHECKS === '0' ? undefined : createSystemCheck({ serviceHome, home: homedir() }), worktrees: {
      opsRepo: process.env.SCK_AGENT_CWD ?? '/Users/y/IdeaProjects/surreal-ck-operations',
      // Same wiring as the plugin process (plugin/server/company.ts): an owner manual reclaim_worktrees
      // through this MCP process must tear the Paseo side down together with the git tree instead
      // of leaving workspaces/projects behind. createSceneCleaner is idempotent, matching the
      // plugin's semantics. Employees in the scene retire with an honest reason first; the
      // plugin's agent.archived listener does the in-process detach on its side.
      sceneCleaner: createSceneCleaner(createPaseoCli(), {
        insts: () => workforce.insts(),
        retire: (id, reason, kind) => workforce.retire(id, reason, kind),
      }),
      orphanGraceDays: process.env.SCK_WORKTREE_ORPHAN_GRACE_DAYS
        ? Number(process.env.SCK_WORKTREE_ORPHAN_GRACE_DAYS) : undefined,
      reclaimEnabled: process.env.SCK_WORKTREE_RECLAIM === '0' || process.env.SCK_WORKTREE_RECLAIM === 'false'
        ? false
        : process.env.SCK_WORKTREE_RECLAIM === '1' || process.env.SCK_WORKTREE_RECLAIM === 'true'
          ? true : undefined,
    } });
  // Public exposure (behind Caddy) requires a shared gate token checked before Bearer auth.
  // The token lives in service_gate:primary, generated by SurrealDB; cached briefly so a
  // DB blip does not flap the gate for already-synced callers.
  const publicHost = process.env.SCK_MCP_PUBLIC_HOST?.trim() || undefined;
  let gateToken: (() => Promise<string | undefined>) | undefined;
  if (publicHost) {
    let cached: string | undefined;
    let lastLoad = 0;
    gateToken = async () => {
      if (cached === undefined || Date.now() - lastLoad > 60_000) {
        try {
          const row = await db.db.select<{ token?: string }>(new RecordId('service_gate', 'primary'));
          if (row?.token) cached = row.token;
          lastLoad = Date.now();
        } catch (error) {
          if (cached === undefined) throw error;
        }
      }
      return cached;
    };
  }
  service = createMcpHttpService({
    core, port, publicHost, gateToken,
    ready: async () => {
      const probe = db.db.select(new RecordId('company_meta', 'installation'));
      const timeout = new Promise<false>(resolve => setTimeout(() => resolve(false), 8_000));
      return Boolean(await Promise.race([probe, timeout]));
    },
    heal: () => db.ensureConnected(),
  });
  console.log(`MCP listening on 127.0.0.1:${service.port}`);

  const credentialFile = process.env.SCK_PROJECTOR_CREDENTIAL_FILE;
  const repository = process.env.SCK_GITHUB_REPOSITORY;
  if (Boolean(credentialFile) !== Boolean(repository)) {
    throw new Error('projection requires both SCK_PROJECTOR_CREDENTIAL_FILE and SCK_GITHUB_REPOSITORY');
  }
  if (credentialFile && repository) {
    const credential = await readPrivateCredential(credentialFile);
    const projector = createGithubProjector({
      core, credential, github: createGhCliGateway(repository),
      statePath: resolve(process.env.SCK_PROJECTION_STATE_FILE ?? '.runtime/gh-projection.json'),
      heal: () => db.ensureConnected(),
    });
    const worker = runProjectionWorker({
      // Projection queries run between long gh calls, outside the healed /mcp path;
      // probe-and-reconnect at the top of every pass so a scoped-out conn self-recovers.
      projector: { runOnce: async () => { await db.ensureConnected(); return projector.runOnce(); } },
      signal: shutdown.signal,
      onResult: ({ projected }) => { if (projected) console.log(`Projected ${projected} outbox events`); },
      onError: (error) => console.error(`GitHub projection failed: ${(error as Error)?.message ?? String(error)}; retry scheduled`),
    });
    process.once('SIGINT', () => shutdown.abort());
    process.once('SIGTERM', () => shutdown.abort());
    await worker;
  } else {
    await new Promise<void>(done => {
      process.once('SIGINT', done);
      process.once('SIGTERM', done);
    });
  }
} finally {
  shutdown.abort();
  await service?.close();
  await db.close();
}
